def get_translator(lang: str):
    """
    Retorna a função `t(texto, **kwargs)` já fixada no idioma `lang`.
    pt-br (ou qualquer idioma não suportado) devolve o texto original sem
    passar por dicionário nenhum.
    """
    lang = (lang or IDIOMA_PADRAO).lower()
    if lang not in TRANSLATIONS:
        lang = IDIOMA_PADRAO

    def t(texto: str, **kwargs) -> str:
        traduzido = TRANSLATIONS.get(lang, {}).get(texto, texto) if lang != IDIOMA_PADRAO else texto
        if kwargs:
            try:
                return traduzido % kwargs
            except (KeyError, ValueError):
                return traduzido
        return traduzido

    return t


def _idioma_da_requisicao_atual() -> str:
    """
    Mesma lógica do context_processor em app/__init__.py (usuário logado
    -> User.language; visitante -> cookie nomdo_lang), só que utilizável
    de DENTRO de uma rota Python, não de um template — usado por `t_flash`
    pra decidir em que idioma gravar uma mensagem flash(), já que ela fica
    congelada na sessão até a PRÓXIMA request renderizar o template.
    """
    from flask import session, request

    try:
        user_id = session.get("user_id")
        if user_id:
            from app.extensions import db
            from app.models import User
            user = db.session.get(User, user_id)
            if user and getattr(user, "language", None):
                return user.language
    except Exception:
        pass

    lang = request.cookies.get("nomdo_lang", IDIOMA_PADRAO)
    return lang if lang in IDIOMAS_SUPORTADOS else IDIOMA_PADRAO


def t_flash(texto: str, **kwargs) -> str:
    """
    Traduz uma string pra usar direto em `flash(t_flash("..."), categoria)`
    dentro de rotas — fora do contexto de template, onde `t` já vem
    injetado pelo context_processor.
    """
    return get_translator(_idioma_da_requisicao_atual())(texto, **kwargs)
